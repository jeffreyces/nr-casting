//! The assignment panel for the two-spells-per-catalyst mod.
//!
//! This module owns the panel's content and state; `window` owns the host. The panel is drawn
//! in its own window rather than into the game's swap chain: a second Present hook on ER's
//! swap chain makes a co-resident class port's HUD stop drawing (verified with ERNativeUI), and
//! no amount of state restoration inside the hook fixes it.
//!
//! Layout: the left weapon and its two dropdowns on the left, the right weapon and its
//! two dropdowns on the right, character/state information in the middle.
//!
//! Spell metadata comes from `nr_casting_spells.txt` beside eldenring.exe, generated by
//! `tools/gen-spell-names.py` from the Paramdex annotations in `Magic.param`:
//!
//! ```text
//! spell_id = Name | school | int | fai | arc | fp | slots
//! ```
//!
//! A spell is offered only when the character owns it (a goods entry in the inventory)
//! **and** the character's INT/FAI/ARC meet its requirement. `show everything` bypasses
//! both, for planning a build the character cannot cast yet.
//!
//! While the panel is open the game's input messages are blocked and the cursor clip is
//! released, so mouse and keyboard belong to ImGui; closing it hands both back.

use std::collections::HashSet;



#[derive(Clone)]
pub struct Spell {
    pub id: i32,
    pub name: String,
    pub school: String,
    pub int: u32,
    pub fai: u32,
    pub arc: u32,
    pub fp: u32,
}

impl Spell {
    fn meets(&self, stats: (u32, u32, u32)) -> bool {
        stats.0 >= self.int && stats.1 >= self.fai && stats.2 >= self.arc
    }

    /// "INT 16 · 12 FP · Sorcery" — only the requirements that are non-zero.
    fn detail(&self) -> String {
        let mut parts = Vec::new();
        if self.int > 0 {
            parts.push(format!("INT {}", self.int));
        }
        if self.fai > 0 {
            parts.push(format!("FAI {}", self.fai));
        }
        if self.arc > 0 {
            parts.push(format!("ARC {}", self.arc));
        }
        parts.push(format!("{} FP", self.fp));
        if !self.school.is_empty() {
            parts.push(self.school.clone());
        }
        parts.join(" · ")
    }
}

/// Whether the panel is listing spells the character cannot cast (planning mode).
///
/// Mirrored here because the slot store needs it too: unloading assignments a character cannot
/// cast must not fight with a player who is deliberately planning a build.
static SHOW_ALL: std::sync::atomic::AtomicBool = std::sync::atomic::AtomicBool::new(false);

/// Whether planning mode is on: assignments are then left alone by the requirement check.
pub(crate) fn show_all() -> bool {
    SHOW_ALL.load(std::sync::atomic::Ordering::Relaxed)
}

pub struct Panel {
    visible: bool,
    spells: Vec<Spell>,
    by_id: std::collections::HashMap<i32, usize>,
    /// base weapon id -> name (upgrade level is the low two digits of the equipped id)
    weapons: std::collections::HashMap<i32, String>,
    filter: String,
    show_all: bool,
    /// Spells the character owns, refreshed when the panel opens.
    owned: HashSet<i32>,
    owned_known: bool,
    /// False until the live param catalogue has been merged in.
    live_applied: bool,
}

impl Panel {
    pub fn new() -> Self {
        let spells = load_spells();
        let by_id = spells
            .iter()
            .enumerate()
            .map(|(i, s)| (s.id, i))
            .collect::<std::collections::HashMap<_, _>>();
        Panel {
            visible: false,
            spells,
            by_id,
            weapons: load_weapon_names(),
            filter: String::new(),
            show_all: false,
            owned: HashSet::new(),
            owned_known: false,
            live_applied: false,
        }
    }

    fn label(&self, id: i32) -> String {
        match self.by_id.get(&id) {
            Some(i) => self.spells[*i].name.clone(),
            None => format!("(unknown {id})"),
        }
    }

    /// "Carian Regal Scepter +10" for an equipped weapon id, or "weapon <id>" if unknown.
    fn weapon_label(&self, id: i32) -> String {
        let upgrade = id % 100;
        let base = id - upgrade;
        match self.weapons.get(&base).or_else(|| self.weapons.get(&id)) {
            Some(name) if upgrade > 0 => format!("{name} +{upgrade}"),
            Some(name) => name.clone(),
            // A weapon the vanilla table does not know: the Recluse port adds its own, and those
            // names live in the port's data, not in Paramdex.
            None => format!("mod weapon {id}"),
        }
    }

    /// Overlay the live catalogue: requirements and costs come from the running game, so a
    /// patch that adds spells is picked up without regenerating anything. Names stay from the
    /// embedded table, because they are not in the params at all.
    ///
    /// Called on panel open rather than at startup: the param repository is not populated when
    /// the DLL loads, and an empty read would silently pin the table for the session.
    /// Load the catalogue: the cached file when there is one, otherwise built from the live
    /// params. Building is deferred to `ensure_catalogue` so the same work can run before the
    /// panel is ever opened.
    fn apply_live_catalogue(&mut self) {
        if self.live_applied {
            return;
        }
        let Some(text) = ensure_catalogue() else {
            return;
        };
        let rows = parse_spells(&text);
        if rows.is_empty() {
            return;
        }
        self.spells = rows;
        self.reindex();
        self.live_applied = true;
    }

    fn reindex(&mut self) {
        // `sort_by_cached_key` lower-cases each name once instead of once per comparison.
        self.spells
            .sort_by_cached_key(|spell| spell.name.to_lowercase());
        self.by_id = self
            .spells
            .iter()
            .enumerate()
            .map(|(i, s)| (s.id, i))
            .collect();
    }

    fn refresh_owned(&mut self) {
        self.apply_live_catalogue();
        let goods: HashSet<i32> = crate::inventory_goods_ids().into_iter().collect();
        let spells: HashSet<i32> = goods
            .iter()
            .copied()
            .filter(|id| self.by_id.contains_key(id))
            .collect();
        self.owned_known = !goods.is_empty();
        crate::log(&format!(
            "panel: {} goods entries, {} of them spells, stats {:?}",
            goods.len(),
            spells.len(),
            crate::player_stats()
        ));
        self.owned = spells;
    }

    /// Owned **and** castable. `show everything` bypasses both gates.
    fn offered(&self, spell: &Spell, stats: Option<(u32, u32, u32)>) -> bool {
        if self.show_all {
            return true;
        }
        if self.owned_known && !self.owned.contains(&spell.id) {
            return false;
        }
        match stats {
            Some(stats) => spell.meets(stats),
            None => false,
        }
    }
}

impl Panel {
    /// Open or close the panel. Ownership of the cursor and any borrowed spell slot follows.
    pub fn set_visible(&mut self, visible: bool) {
        if self.visible == visible {
            return;
        }
        self.visible = visible;
        crate::UI_OPEN.store(visible, std::sync::atomic::Ordering::Relaxed);
        crate::pointer::set_open(visible);
        if visible {
            self.refresh_owned();
        }
        // Closing does not touch game memory: the borrow is released on the next pad poll, which
        // is the game's own thread. Writing it here would race the game's teardown of the
        // character (a warp, a death, a load) and corrupt the heap.
    }


    /// Everything the window needs to fill a slot's list, already filtered.
    pub fn candidates(&self, needle: &str) -> Vec<(i32, String)> {
        let needle = needle.trim().to_ascii_lowercase();
        let stats = crate::player_stats();
        self.spells
            .iter()
            .filter(|spell| self.offered(spell, stats))
            .filter(|spell| {
                needle.is_empty()
                    || spell.name.to_ascii_lowercase().contains(&needle)
                    || spell.id.to_string().contains(&needle)
            })
            .map(|spell| (spell.id, format!("{}   {}", spell.name, spell.detail())))
            .collect()
    }

    pub fn assign(&self, weapon: i32, slot: usize, id: i32) {
        if weapon <= 0 {
            return;
        }
        crate::store_set(weapon, slot, id);
        crate::log(&format!(
            "panel: slot {slot} on {weapon} = spell {id} ({})",
            self.label(id)
        ));
    }

    pub fn slot_value(&self, weapon: i32, slot: usize) -> i32 {
        crate::store_get(weapon).map(|pair| pair[slot]).unwrap_or(-1)
    }

    /// Re-read everything that changes while the game runs.
    pub fn reload(&mut self) {
        self.apply_live_catalogue();
        self.refresh_owned();
    }

    pub fn set_filter(&mut self, needle: String) {
        self.filter = needle;
    }

    pub fn set_show_all(&mut self, show: bool) {
        self.show_all = show;
        SHOW_ALL.store(show, std::sync::atomic::Ordering::Relaxed);
    }

    pub fn spell_name(&self, id: i32) -> String {
        self.label(id)
    }

    pub fn spell_count(&self) -> usize {
        self.spells.len()
    }

    pub fn weapon_name(&self, id: i32) -> String {
        self.weapon_label(id)
    }
}

const WEAPONS_TABLE: &str = include_str!("../data/nr_casting_weapons.txt");
const SPELLS_TABLE: &str = include_str!("../data/nr_casting_spells.txt");

fn table_text(name: &str, embedded: &'static str) -> (String, &'static str) {
    match std::fs::read_to_string(crate::config::read_path(name)) {
        Ok(text) => (text, "file"),
        Err(_) => (embedded.to_string(), "embedded"),
    }
}

/// Base weapon ids the vanilla table knows, built once from the embedded copy.
fn vanilla_weapons() -> &'static std::collections::HashSet<i32> {
    static SET: std::sync::OnceLock<std::collections::HashSet<i32>> = std::sync::OnceLock::new();
    SET.get_or_init(|| {
        WEAPONS_TABLE
            .lines()
            .filter_map(|line| line.split('#').next())
            .filter_map(|line| line.split_once('='))
            .filter_map(|(id, _)| id.trim().parse::<i32>().ok())
            .collect()
    })
}

/// Whether a weapon id came from the base game rather than from a content mod.
///
/// Paired weapons carry their upgrade level in the low two digits, so the base id is what the
/// table lists. A class port ships its own catalysts, and those are exactly the ids that are
/// missing here — which is how a Recluse character is recognised without knowing its chr id.
pub(crate) fn is_vanilla_weapon(id: i32) -> bool {
    id <= 0 || vanilla_weapons().contains(&(id - id % 100))
}

fn load_weapon_names() -> std::collections::HashMap<i32, String> {
    let (text, source) = table_text("nr_casting_weapons.txt", WEAPONS_TABLE);
    let mut map = std::collections::HashMap::new();
    for line in text.lines() {
        let line = line.split('#').next().unwrap_or("").trim();
        if let Some((id, name)) = line.split_once('=') {
            if let (Ok(id), name) = (id.trim().parse::<i32>(), name.trim()) {
                if !name.is_empty() {
                    map.insert(id, name.to_string());
                }
            }
        }
    }
    crate::log(&format!(
        "table: {} weapons from the {source} copy",
        map.len()
    ));
    map
}

/// Build the spell catalogue from the running game, or return the cached copy.
///
/// Numbers and row ids come from the live `Magic` param, so a patch that adds or changes
/// spells is picked up without regenerating anything. Names are the one thing the params do
/// not carry — they come from the table compiled into the DLL — so a spell the table does not
/// know yet appears as `Spell <id>` until the table is refreshed.
///
/// The result is written to `nr_casting_catalogue.txt` beside the DLL and reused verbatim on
/// later launches; `run()` deletes it when the executable's fingerprint changes, so a stale
/// catalogue cannot outlive the build it describes. Returns `None` while the game has not
/// loaded its regulation yet.
pub(crate) fn ensure_catalogue() -> Option<String> {
    // Read from either location, but always write into the mod's own folder.
    let cache = crate::config::path("nr_casting_catalogue.txt");
    if let Ok(text) = std::fs::read_to_string(crate::config::read_path("nr_casting_catalogue.txt")) {
        if !text.trim().is_empty() {
            return Some(text);
        }
    }

    let live = crate::params::live_spells();
    if live.is_empty() {
        return None;
    }

    let (table, _source) = table_text("nr_casting_spells.txt", SPELLS_TABLE);
    let mut spells = parse_spells(&table);
    let mut by_id: std::collections::HashMap<i32, usize> =
        spells.iter().enumerate().map(|(i, s)| (s.id, i)).collect();
    let mut added = 0usize;
    for row in &live {
        match by_id.get(&row.id).copied() {
            Some(index) => {
                let spell = &mut spells[index];
                spell.int = row.int;
                spell.fai = row.fai;
                spell.arc = row.arc;
                spell.fp = row.fp;
            }
            None => {
                added += 1;
                by_id.insert(row.id, spells.len());
                spells.push(Spell {
                    id: row.id,
                    name: format!("Spell {}", row.id),
                    school: String::new(),
                    int: row.int,
                    fai: row.fai,
                    arc: row.arc,
                    fp: row.fp,
                });
            }
        }
    }
    spells.sort_by_key(|s| s.id);

    let mut out = String::from(
        "# generated from the running game's Magic param\n\
         # spell_id = Name | school | int | fai | arc | fp\n",
    );
    for spell in &spells {
        out.push_str(&format!(
            "{} = {} | {} | {} | {} | {} | {}\n",
            spell.id, spell.name, spell.school, spell.int, spell.fai, spell.arc, spell.fp
        ));
    }
    if let Err(e) = std::fs::write(&cache, &out) {
        crate::log(&format!("catalogue: could not write {}: {e}", cache.display()));
    }
    crate::log(&format!(
        "params: {} live spell rows applied ({added} not in the table), catalogue cached",
        live.len()
    ));
    report_weapon_drift();
    Some(out)
}

/// The table only supplies weapon names, and a game update can add rows it has never seen.
/// Say so in the log, with examples, so a stale table is visible instead of silent.
fn report_weapon_drift() {
    let live = crate::params::live_weapon_ids();
    if live.is_empty() {
        return;
    }
    let names = load_weapon_names();
    let mut unknown: Vec<i32> = live
        .iter()
        .copied()
        .filter(|id| !names.contains_key(id))
        .collect();
    unknown.sort_unstable();
    // Rows without a name are normal: Paramdex only names entries the community cared about,
    // so dummy and NPC-only weapon rows are unnamed in every build. The number that moves is
    // the live total — a patch that adds player weapons raises it, and those ids are the ones
    // a regenerated table would newly cover.
    let sample: Vec<String> = unknown.iter().take(6).map(|id| id.to_string()).collect();
    crate::log(&format!(
        "weapons: {} live rows, {} named, {} unnamed{} (unnamed = dummy/NPC rows; regenerate only if a patch adds weapons)",
        live.len(),
        live.len() - unknown.len(),
        unknown.len(),
        if unknown.is_empty() {
            String::new()
        } else {
            format!(" (e.g. {})", sample.join(", "))
        }
    ));
}

fn parse_spells(text: &str) -> Vec<Spell> {
    let mut out = Vec::new();
    {
        for line in text.lines() {
            let line = line.split('#').next().unwrap_or("").trim();
            let Some((id, rest)) = line.split_once('=') else {
                continue;
            };
            let Ok(id) = id.trim().parse::<i32>() else {
                continue;
            };
            let fields: Vec<&str> = rest.split('|').map(str::trim).collect();
            let num = |i: usize| {
                fields
                    .get(i)
                    .and_then(|v| v.parse::<u32>().ok())
                    .unwrap_or(0)
            };
            out.push(Spell {
                id,
                name: fields.first().copied().unwrap_or("").to_string(),
                school: fields.get(1).copied().unwrap_or("").to_string(),
                int: num(2),
                fai: num(3),
                arc: num(4),
                fp: num(5),
            });
        }
    }
    for spell in out.iter_mut() {
        if spell.name.is_empty() {
            spell.name = format!("Spell {}", spell.id);
        }
    }
    out.sort_by_cached_key(|spell| spell.name.to_lowercase());
    out
}

fn load_spells() -> Vec<Spell> {
    let (text, source) = table_text("nr_casting_spells.txt", SPELLS_TABLE);
    let out = parse_spells(&text);
    crate::log(&format!("table: {} spells from the {source} copy", out.len()));
    out
}
